        static bool TryGetMapObjectName(string name, out string translated) {
            var names = CurrentMapObjects;
            translated = null;
            return names != null && names.TryGetValue(name, out translated);
        }

        // Use only for built-in map objects, never for names entered by the player.
        static readonly Dictionary<AppLanguage, Dictionary<string,string>> MapNameCache = new Dictionary<AppLanguage, Dictionary<string,string>>();
        static readonly object MapNameCacheLock = new object();
        public static string GetMapObjectName(string englishName) {
            if (string.IsNullOrEmpty(englishName)) return string.Empty;
            if (Current == AppLanguage.English) return englishName;
            lock (MapNameCacheLock) {
                Dictionary<string,string> names;
                if (!MapNameCache.TryGetValue(Current, out names)) {
                    names = new Dictionary<string,string>(StringComparer.Ordinal);
                    MapNameCache.Add(Current, names);
                }
                string translated;
                if (names.TryGetValue(englishName, out translated)) return translated;
                translated = TranslateMapObjectName(englishName);
                // Bound each language's cache even if imported maps contain many names.
                if (names.Count < 32768) names.Add(englishName, translated);
                return translated;
            }
        }

        static string TranslateMapObjectName(string englishName) {
            string exact = GetZoneName(englishName);
            if (exact != englishName) return exact;
            var objects = CurrentMapObjects;
            if (objects != null) return TranslateMapObject(englishName, objects, CurrentMapCategories);
            return englishName;
        }

        static string TranslateMapObject(string name, Dictionary<string,string> objects, Dictionary<string,string> categories) {
            string translated;
            if (objects.TryGetValue(name, out translated) || categories.TryGetValue(name, out translated)) return translated;
            if (name.StartsWith("Gas Station - ", StringComparison.OrdinalIgnoreCase))
                return objects["Gas Station"] + " - " + TranslateMapObject(name.Substring(14), objects, categories);
            var sector = System.Text.RegularExpressions.Regex.Match(name, @" \([DCBAZ][0-4]\)$");
            if (sector.Success)
                return TranslateMapObject(name.Substring(0, sector.Index), objects, categories) + sector.Value;
            // Generated labels retain their settlement/sector prefix and translate the longest known type.
            string bestKey = null, bestValue = null;
            foreach (var table in new[] { objects, categories }) {
                foreach (var entry in table) {
                    if ((bestKey == null || entry.Key.Length > bestKey.Length) &&
                        name.EndsWith(" " + entry.Key, StringComparison.OrdinalIgnoreCase)) {
                        bestKey = entry.Key; bestValue = entry.Value;
                    }
                }
            }
            return bestKey == null ? name : name.Substring(0, name.Length - bestKey.Length) + bestValue;
        }
