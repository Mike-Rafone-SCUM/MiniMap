        static Dictionary<string,string> BuildMapObjects(int column) {
            return BuildMapObjects(MapObjectTranslations, column, 3);
        }

        static Dictionary<string,string> BuildMapObjects(string table, int column, int columns) {
            var result = new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase);
            foreach (string row in table.Split('\n')) {
                string[] fields = row.TrimEnd('\r').Split('|');
                if (fields.Length != columns) throw new FormatException("Invalid map object translation row.");
                result.Add(fields[0], fields[column]);
            }
            return result;
        }

        static Dictionary<string,string> BuildRussianZoneNames() {
            return BuildZoneNames(MapObjectsRu, CategoryNamesRu);
        }

        static Dictionary<string,string> BuildZoneNames(Dictionary<string,string> objects, Dictionary<string,string> categories) {
            var result = new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase);
            foreach (string name in ZoneNamesEsAr.Keys) {
                result.Add(name, TranslateMapObject(name, objects, categories));
            }
            return result;
        }

