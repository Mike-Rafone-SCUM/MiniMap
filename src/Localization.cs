namespace ScumMiniMap {
    public enum AppLanguage {
        English = 0,
        SpanishArgentina = 1,
        French = 2,
        German = 3,
        Dutch = 4,
        Russian = 5,
        Chinese = 6,
        Turkish = 7,
        Arabic = 8
    }

    public static class Localization {
        public static event Action LanguageChanged;

        private static AppLanguage currentLanguage = AppLanguage.English;

        public static AppLanguage Current {
            get { return currentLanguage; }
            set {
                if (currentLanguage != value) {
                    currentLanguage = value;
                    Action handler = LanguageChanged;
                    if (handler != null) handler();
                }
            }
        }

        public static string CurrentCode {
            get {
                switch (currentLanguage) {
                    case AppLanguage.SpanishArgentina: return "es-AR";
                    case AppLanguage.French: return "fr";
                    case AppLanguage.German: return "de";
                    case AppLanguage.Dutch: return "nl";
                    case AppLanguage.Russian: return "ru";
                    case AppLanguage.Chinese: return "zh-CN";
                    case AppLanguage.Turkish: return "tr";
                    case AppLanguage.Arabic: return "ar";
                    default: return "en";
                }
            }
        }

        public static void SetLanguage(string code) {
            if (string.IsNullOrWhiteSpace(code)) return;
            string normalized = code.Trim().ToLowerInvariant();
            if (normalized.StartsWith("es")) {
                Current = AppLanguage.SpanishArgentina;
            } else if (normalized.StartsWith("fr")) {
                Current = AppLanguage.French;
            } else if (normalized.StartsWith("de")) {
                Current = AppLanguage.German;
            } else if (normalized.StartsWith("nl")) {
                Current = AppLanguage.Dutch;
            } else if (normalized.StartsWith("ru")) {
                Current = AppLanguage.Russian;
            } else if (normalized.StartsWith("zh")) {
                Current = AppLanguage.Chinese;
            } else if (normalized.StartsWith("tr")) {
                Current = AppLanguage.Turkish;
            } else if (normalized.StartsWith("ar")) {
                Current = AppLanguage.Arabic;
            } else {
                Current = AppLanguage.English;
            }
        }

        public static void DetectSystemLanguage() {
            try {
                string name = CultureInfo.CurrentUICulture.Name.ToLowerInvariant();
                if (name.StartsWith("es")) {
                    Current = AppLanguage.SpanishArgentina;
                } else if (name.StartsWith("fr")) {
                    Current = AppLanguage.French;
                } else if (name.StartsWith("de")) {
                    Current = AppLanguage.German;
                } else if (name.StartsWith("nl")) {
                    Current = AppLanguage.Dutch;
                } else if (name.StartsWith("ru")) {
                    Current = AppLanguage.Russian;
                } else if (name.StartsWith("zh")) {
                    Current = AppLanguage.Chinese;
                } else if (name.StartsWith("tr")) {
                    Current = AppLanguage.Turkish;
                } else if (name.StartsWith("ar")) {
                    Current = AppLanguage.Arabic;
                } else {
                    Current = AppLanguage.English;
                }
            } catch {
                Current = AppLanguage.English;
            }
        }

        public static string Get(string key) {
            if (string.IsNullOrEmpty(key)) return string.Empty;
            Dictionary<string, string> dict = null;
            switch (currentLanguage) {
                case AppLanguage.SpanishArgentina: dict = StringsEsAr; break;
                case AppLanguage.French: dict = StringsFr; break;
                case AppLanguage.German: dict = StringsDe; break;
                case AppLanguage.Dutch: dict = StringsNl; break;
                case AppLanguage.Russian: dict = StringsRu; break;
                case AppLanguage.Chinese: dict = StringsZh; break;
                case AppLanguage.Turkish: dict = StringsTr; break;
                case AppLanguage.Arabic: dict = StringsAr; break;
                default: dict = StringsEn; break;
            }
            string value;
            if (dict != null && dict.TryGetValue(key, out value)) {
                return value;
            }
            if (StringsEn != null && StringsEn.TryGetValue(key, out value)) {
                return value;
            }
            return key;
        }

        public static string T(string key, params object[] args) {
            string text = Get(key);
            if (args == null || args.Length == 0) return text;
            try {
                return string.Format(CultureInfo.InvariantCulture, text, args);
            } catch {
                return text;
            }
        }

        public static string GetZoneName(string englishName) {
            if (string.IsNullOrEmpty(englishName)) return string.Empty;
            if (currentLanguage == AppLanguage.SpanishArgentina) {
                string localized;
                if (ZoneNamesEsAr != null && ZoneNamesEsAr.TryGetValue(englishName, out localized)) {
                    return localized;
                }
                if (englishName.StartsWith("Gas Station - ", StringComparison.OrdinalIgnoreCase)) {
                    string sub = englishName.Substring("Gas Station - ".Length);
                    string locSub;
                    if (ZoneNamesEsAr != null && ZoneNamesEsAr.TryGetValue(sub, out locSub)) {
                        return "Estación de Servicio - " + locSub;
                    }
                    return "Estación de Servicio - " + sub;
                }
            }
            return englishName;
        }

        public static string GetSectionName(string section) {
            if (string.IsNullOrEmpty(section)) return string.Empty;
            Dictionary<string, string> dict = null;
            switch (currentLanguage) {
                case AppLanguage.SpanishArgentina: dict = SectionNamesEsAr; break;
                case AppLanguage.French: dict = SectionNamesFr; break;
                case AppLanguage.German: dict = SectionNamesDe; break;
                case AppLanguage.Dutch: dict = SectionNamesNl; break;
                case AppLanguage.Russian: dict = SectionNamesRu; break;
                case AppLanguage.Chinese: dict = SectionNamesZh; break;
                case AppLanguage.Turkish: dict = SectionNamesTr; break;
                case AppLanguage.Arabic: dict = SectionNamesAr; break;
            }
            if (dict != null) {
                string loc;
                if (dict.TryGetValue(section, out loc)) return loc;
            }
            return section;
        }

        public static string GetCategoryName(string category) {
            if (string.IsNullOrEmpty(category)) return string.Empty;
            Dictionary<string, string> dict = null;
            switch (currentLanguage) {
                case AppLanguage.SpanishArgentina: dict = CategoryNamesEsAr; break;
                case AppLanguage.French: dict = CategoryNamesFr; break;
                case AppLanguage.German: dict = CategoryNamesDe; break;
                case AppLanguage.Dutch: dict = CategoryNamesNl; break;
                case AppLanguage.Russian: dict = CategoryNamesRu; break;
                case AppLanguage.Chinese: dict = CategoryNamesZh; break;
                case AppLanguage.Turkish: dict = CategoryNamesTr; break;
                case AppLanguage.Arabic: dict = CategoryNamesAr; break;
            }
            if (dict != null) {
                string loc;
                if (dict.TryGetValue(category, out loc)) return loc;
            }
            return category;
        }

        public static void SelfTest() {
            if (string.IsNullOrEmpty(Get("Settings"))) throw new Exception("Localization self-test failed: missing English string.");
            AppLanguage prev = Current;
            try {
                AppLanguage[] allLangs = new AppLanguage[] {
                    AppLanguage.SpanishArgentina,
                    AppLanguage.French,
                    AppLanguage.German,
                    AppLanguage.Dutch,
                    AppLanguage.Russian,
                    AppLanguage.Chinese,
                    AppLanguage.Turkish,
                    AppLanguage.Arabic
                };
                foreach (AppLanguage l in allLangs) {
                    Current = l;
                    if (string.IsNullOrEmpty(Get("Settings"))) throw new Exception("Localization self-test failed: missing string for " + l);
                    if (string.IsNullOrEmpty(GetCategoryName("Bunkers"))) throw new Exception("Localization self-test failed: missing category translation for " + l);
                }
            } finally {
                Current = prev;
            }
        }
